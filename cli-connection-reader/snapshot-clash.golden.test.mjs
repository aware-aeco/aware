// Pair-mode clash must not move when single-mode clash, `minOverlap`, per-rule pairs and the bounded broad phase arrive
// (model-change-set 0.6.0). The files in test-fixtures/check-clash-pair-golden/ are the canonical output of the 0.5.0 code
// (origin/main ff2e81683) for the inputs in snapshot-clash-golden-inputs.mjs. A v1 profile must give those bytes exactly;
// a v2 profile may differ only in its `evaluator` block (the version, and the `evaluator.geometry` echo added in 0.6.0).
import test from 'node:test';
import assert from 'node:assert/strict';
import { readdirSync, readFileSync } from 'node:fs';
import { canonicalJson } from './snapshot-compare.mjs';
import { checkSnapshots, EVALUATOR_VERSION } from './snapshot-check.mjs';
import { loadClashEngine } from './snapshot-clash.mjs';
import { CASES } from './snapshot-clash-golden-inputs.mjs';

const engine = await loadClashEngine();
const dir = new URL('./test-fixtures/check-clash-pair-golden/', import.meta.url);
const golden = (name) => readFileSync(new URL(`${name}.json`, dir), 'utf8');

test('every clash golden case has a file and every file has a case', () => {
  assert.deepEqual(readdirSync(dir).map((f) => f.replace(/\.json$/, '')).sort(), Object.keys(CASES).sort());
});

for (const [name, make] of Object.entries(CASES)) {
  test(`pair-mode clash output is byte-identical to the 0.5.0 golden: ${name}`, () => {
    const out = checkSnapshots({ ...make(), engine });
    const expected = golden(name);
    if (out.evaluator) {
      assert.equal(out.evaluator.version, EVALUATOR_VERSION);
      assert.deepEqual(Object.keys(out.evaluator.geometry).sort(), ['budgets', 'contactTolerance', 'minOverlap', 'pairs', 'weldTolerance']);
      assert.equal(out.evaluator.geometry.minOverlap, out.evaluator.geometry.contactTolerance, 'no minOverlap given: it is the contact tolerance');
      const { geometry: _added, ...rest } = out.evaluator;
      out.evaluator = { ...rest, version: JSON.parse(expected).evaluator.version };
    }
    assert.equal(canonicalJson(out), expected);
  });
}

test('the clash goldens exercise what they claim to (overlap, contact, a bolted gap, own joints, approximate and missing solids, v2)', () => {
  const read = (name) => JSON.parse(golden(name));
  const rules = (name) => new Set(read(name).findings.map((f) => f.ruleId));
  assert.ok(rules('busy').has('clash.interpenetration') && read('busy').focusSets.length > 0);
  assert.ok(rules('quality').has('clash.bolted-plies-apart') && rules('quality').has('clash.unjoined-contact'));
  assert.ok(read('quality').scope.solids.approximate > 0 && read('quality').scope.solids.noGeometry > 0);
  assert.ok(read('joints').scope.notEvaluated.byReason['own-joint'] > 0);
  assert.equal(read('v2').evaluator.version, '0.5.0', 'the golden was generated by the 0.5.0 code');
  assert.equal(read('busy').evaluator, undefined, 'a v1 document carries no evaluator');
});
